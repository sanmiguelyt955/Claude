"""HTTP server that exposes the Google Cloud analysis produced in this folder.

Reads the JSON/CSV/PNG artifacts generated by fetch.py, graph.py and render.py.
Nothing is fetched from Google at request time.

Run locally:
    uvicorn server:app --reload --port 8080
"""

import csv
import json
import os
from pathlib import Path

from fastapi import FastAPI, HTTPException, Query
from fastapi.responses import FileResponse

BASE = Path(__file__).resolve().parent
PNG = BASE / "grafo_dependencias_gcp.png"

app = FastAPI(
    title="Google Cloud analysis",
    description="Service catalog, per-service API stats and cross-service mention graph.",
    version="1.0.0",
)


def _load_json(name: str):
    with open(BASE / name, encoding="utf-8") as f:
        return json.load(f)


def _load_edges():
    with open(BASE / "edges_all.csv", newline="", encoding="utf-8") as f:
        return [
            {
                "source": r["source"],
                "target": r["target"],
                "mentions": int(r["mentions"]),
                "target_is_control_plane": r["target_is_control_plane"] == "True",
            }
            for r in csv.DictReader(f)
        ]


STATS = _load_json("cloud_stats.json")
MENTIONS = _load_json("mentions.json")
EDGES = _load_edges()


@app.get("/health")
def health():
    return {"status": "ok", "services": sum(1 for v in STATS.values() if "error" not in v)}


@app.get("/services")
def list_services():
    """All services with API stats (methods, resources, schemas, version, host)."""
    return {
        name: info
        for name, info in sorted(STATS.items())
        if "error" not in info
    }


@app.get("/services/{name}")
def get_service(name: str):
    info = STATS.get(name)
    if info is None or "error" in info:
        raise HTTPException(status_code=404, detail=f"unknown service: {name}")
    return {
        "name": name,
        "stats": info,
        "depends_on": sorted(
            (
                {"target": t, "mentions": c}
                for t, c in MENTIONS.get(name, {}).items()
            ),
            key=lambda x: -x["mentions"],
        ),
        "depended_on_by": sorted(
            (
                {"source": e["source"], "mentions": e["mentions"]}
                for e in EDGES
                if e["target"] == name
            ),
            key=lambda x: -x["mentions"],
        ),
    }


@app.get("/edges")
def list_edges(
    min_mentions: int = Query(10, ge=1, description="Drop edges below this count."),
    include_control_plane: bool = Query(True, description="Include edges into IAM / Resource Manager."),
    limit: int = Query(200, ge=1, le=1000),
):
    out = [
        e
        for e in EDGES
        if e["mentions"] >= min_mentions
        and (include_control_plane or not e["target_is_control_plane"])
    ]
    out.sort(key=lambda e: -e["mentions"])
    return {"count": len(out), "edges": out[:limit]}


@app.get("/graph.png")
def graph_png():
    if not PNG.exists():
        raise HTTPException(status_code=404, detail="graph image not generated")
    return FileResponse(PNG, media_type="image/png")
